let a = 5;
let b = 2;

// Arithmetic operators
console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);

// a++ increases the value by 1
a++;
console.log(a);

// a += 4 means a = a + 4
a += 4;
console.log(a);

// Comparison and logical operators
console.log(a == b);
console.log(a > b && a > 0);
console.log(a < b || a > 0);

// Ternary operator is a short way to write if-else
let age = 18;
let result = age >= 18 ? "can vote" : "cannot vote";
console.log(result);
